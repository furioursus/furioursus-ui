/** Every generated file, keyed by path relative to the repo root. */
export function build(tokens = loadTokens()) {
	return {
		"dist/tokens.css": tokensCss(tokens),
		"dist/base.css": baseCss(tokens),
		"dist/tailwind.css": tailwindCss(tokens),
		"dist/theme.js": themeJs(tokens),
		"dist/tokens.json": tokensJson(tokens),
		"docs/reference.md": referenceMd(tokens),
		"demo/index.html": demoHtml(tokens),
	};
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	for (const [path, content] of Object.entries(build())) {
		mkdirSync(dirname(join(root, path)), { recursive: true });
		writeFileSync(join(root, path), content);
		console.log(`wrote ${path}`);
	}
}
